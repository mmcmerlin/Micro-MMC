void Process_ADC_data(void)
{
	uint16_t *buffer = &dma_buffer[bufferStart];
	i1_sum = 0, i2_sum = 0, v1_sum = 0, v2_sum = 0, vsm_sum = 0, vref_sum = 0, cpu_temp_sum = 0;
	for (int i = 0; i < DMA_SAMPLES; ++i) {
		i1_sum += buffer[0];
		i2_sum += buffer[1];
		v1_sum += buffer[2];
		v2_sum += buffer[3];
		vsm_sum += buffer[4];
		vref_sum += buffer[5];
		cpu_temp_sum += buffer[6];

		// move pointer to the next sequence
		buffer += ADC_CHANNELS;
		}

	vref_avg = (vref_sum >> DMA_SAMPLES_BIT);
	i1_avg = (int32_t)(i1_sum >> DMA_SAMPLES_BIT) - vref_avg;
	i2_avg = (int32_t)(i2_sum >> DMA_SAMPLES_BIT) - vref_avg;
	v1_avg = (v1_sum >> DMA_SAMPLES_BIT);
	v2_avg = (v1_sum >> DMA_SAMPLES_BIT);
	vsm_avg = (vsm_sum >> DMA_SAMPLES_BIT);
	cpu_temp_avg = (cpu_temp_sum >> DMA_SAMPLES_BIT);

	/*
	// VDDA can be calculated based on the measured vref and the calibration data
	vdda = (float) VREFINT_CAL_VREF * (float) *VREFINT_CAL_ADDR / vref_avg / 1000;

	// Knowing vdda and the resolution of adc - the actual voltage can be calculated
	vref = (float) vdda / ADC_RESOLUTION * vref_avg;

	// Temperature can be calculated based on the
	temp = (float) ((float) ((float) (TEMPSENSOR_CAL2_TEMP - TEMPSENSOR_CAL1_TEMP) / (float) (*TEMPSENSOR_CAL2_ADDR - *TEMPSENSOR_CAL1_ADDR)) * (temp_avg *TEMPSENSOR_CAL1_ADDR) + TEMPSENSOR_CAL1_TEMP);
	*/

	processData_flag = 0;

	return;
}

