/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_DAC1_Init();
  MX_TIM1_Init();
  MX_TIM2_Init();
  MX_TIM3_Init();
  MX_ADC1_Init();
  MX_USART1_UART_Init();
  /* USER CODE BEGIN 2 */

	  // calibrate ADC for better accuracy
	if(HAL_ADCEx_Calibration_Start(&hadc1) != HAL_OK)
	  Error_Handler();

		  // Set the DC value for the DAC
	DAC1->DHR12R2 = DAC_OFFSET;
	HAL_DAC_Start(&hdac1, DAC_CHANNEL_2);

		  // Start the DMA triggered ADC
	if(HAL_ADC_Start_DMA(&hadc1, (uint32_t*) &dma_buffer, 2 * DMA_BUFFER_SIZE) != HAL_OK)
	  Error_Handler();

		  // Set up the receiving link
	HAL_UART_Receive_DMA(&huart1, UART1_rxBuffer, MESSAGE_LENGTH);

		  // Enable Pins for H-Bridges & Activate Timer 1 for PWM
	HAL_TIM_PWM_Start_DMA(&htim1, TIM_CHANNEL_1, (uint32_t *) cos_A640_M110_PH000_THI_table, COS_TABLE_LENGTH);
	HAL_TIM_PWM_Start_DMA(&htim1, TIM_CHANNEL_2, (uint32_t *) cos_A640_M110_PH090_THI_table, COS_TABLE_LENGTH);
	TIM1->CCR3 = 64; // To account for the 500ns delay in bridge switching - to be moved to CCR4

		  // Enable the Motor Drive outputs
	HAL_GPIO_WritePin(EN1_GPIO_Port, EN1_Pin, GPIO_PIN_SET);
	HAL_GPIO_WritePin(EN2_GPIO_Port, EN2_Pin, GPIO_PIN_SET);


  // Activate heartbeat patterns for LEDs
    // STAT LED
  HAL_TIM_PWM_Start_DMA(&htim3, TIM_CHANNEL_1, (uint32_t *) heartbeat_1Hz_A10000_table, HEARTBEAT_LENGTH);
    // COM LED
  HAL_TIM_PWM_Start_DMA(&htim3, TIM_CHANNEL_2, (uint32_t *) heartbeat_2Hz_A10000_table, HEARTBEAT_LENGTH);

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */

	  if(processData_flag)
	  {
		  Process_ADC_data();
	  }

	  // Sleep this next interruption
	  HAL_SuspendTick();
	  HAL_PWR_EnterSLEEPMode(PWR_MAINREGULATOR_ON, PWR_SLEEPENTRY_WFI);
  }
  /* USER CODE END 3 */
}

